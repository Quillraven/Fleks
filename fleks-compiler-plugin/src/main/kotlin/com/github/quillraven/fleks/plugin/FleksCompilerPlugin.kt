const val FLEKS_PLUGIN_ID = "io.github.quillraven.fleks.compiler-plugin"

private val COMPONENT_ANNOTATION_FQN = FqName("com.github.quillraven.fleks.FleksComponent")
private val COMPONENT_ANNOTATION_CLASS_ID = ClassId.topLevel(COMPONENT_ANNOTATION_FQN)
private val COMPONENT_CLASS_ID = ClassId.fromString("com/github/quillraven/fleks/Component")
private val COMPONENT_TYPE_CLASS_ID = ClassId.fromString("com/github/quillraven/fleks/ComponentType")
private val TYPE_FUNCTION_NAME = Name.identifier("type")

/** Key that tags all declarations generated by this plugin — used to link FIR → IR. */
private data object FleksPluginKey : GeneratedDeclarationKey()

private val componentAnnotationPredicate = DeclarationPredicate.create { annotated(COMPONENT_ANNOTATION_FQN) }

/** Creates `Class<Self>` for a runtime class with a single type parameter, e.g. `Component<Position>`. */
private fun FirSession.selfParameterizedType(classId: ClassId, self: FirClassSymbol<*>): ConeClassLikeType? =
    symbolProvider.getClassLikeSymbolByClassId(classId)
        ?.constructType(arrayOf(self.constructStarProjectedType(isMarkedNullable = false)), isMarkedNullable = false)

/**
 * Adds `Component<Self>` as a supertype to every class annotated with `@FleksComponent`
 * and `ComponentType<Self>` to its companion object if the companion is user defined and not yet a `ComponentType`.
 */
private class FleksSupertypeGenerationExtension(session: FirSession) : FirSupertypeGenerationExtension(session) {
    override fun FirDeclarationPredicateRegistrar.registerPredicates() {
        register(componentAnnotationPredicate)
    }

    override fun needTransformSupertypes(declaration: FirClassLikeDeclaration): Boolean =
        declaration.hasAnnotation(COMPONENT_ANNOTATION_CLASS_ID, session) || declaration.componentOfCompanion() != null

    override fun computeAdditionalSupertypes(
        classLikeDeclaration: FirClassLikeDeclaration,
        resolvedSupertypes: List<FirResolvedTypeRef>,
        typeResolver: TypeResolveService,
    ): List<ConeKotlinType> {
        if (classLikeDeclaration.hasAnnotation(COMPONENT_ANNOTATION_CLASS_ID, session)) {
            val self = classLikeDeclaration.symbol as? FirClassSymbol<*> ?: return emptyList()
            return listOfNotNull(session.selfParameterizedType(COMPONENT_CLASS_ID, self))
        }

        val alreadyComponentType = resolvedSupertypes.any { it.coneType.classId == COMPONENT_TYPE_CLASS_ID }
        val component = classLikeDeclaration.componentOfCompanion()
        if (alreadyComponentType || component == null) return emptyList()
        return listOfNotNull(session.selfParameterizedType(COMPONENT_TYPE_CLASS_ID, component))
    }

    /** Returns the `@FleksComponent` class that owns this declaration if it is its companion object. */
    private fun FirClassLikeDeclaration.componentOfCompanion(): FirClassSymbol<*>? {
        if (this !is FirRegularClass || !isCompanion) return null
        val owner = session.symbolProvider.getClassLikeSymbolByClassId(symbol.classId.outerClassId ?: return null)
        return (owner as? FirRegularClassSymbol)?.takeIf { it.hasAnnotation(COMPONENT_ANNOTATION_CLASS_ID, session) }
    }
}

/**
 * Generates for every class annotated with `@FleksComponent`
 * - a companion object that is a `ComponentType<Self>` (if the class has no companion yet) and
 * - the `type()` function (if the class does not declare it) that returns the companion.
 */
private class FleksDeclarationGenerationExtension(session: FirSession) : FirDeclarationGenerationExtension(session) {
    override fun FirDeclarationPredicateRegistrar.registerPredicates() {
        register(componentAnnotationPredicate)
    }

    private fun FirClassSymbol<*>.isComponentClass(): Boolean =
        this is FirRegularClassSymbol && hasAnnotation(COMPONENT_ANNOTATION_CLASS_ID, session)

    private fun FirClassSymbol<*>.isGeneratedCompanion(): Boolean = isCompanion && origin == Plugin(FleksPluginKey)

    @OptIn(DirectDeclarationsAccess::class)
    private fun FirClassSymbol<*>.declaresType(): Boolean = declarationSymbols.any {
        it is FirNamedFunctionSymbol && it.name == TYPE_FUNCTION_NAME && it.valueParameterSymbols.isEmpty()
    }

    @OptIn(SymbolInternals::class)
    override fun getNestedClassifiersNames(
        classSymbol: FirClassSymbol<*>,
        context: NestedClassGenerationContext,
    ): Set<Name> {
        val needsCompanion = classSymbol.isComponentClass() &&
            (classSymbol as FirRegularClassSymbol).companionObjectSymbol == null
        return if (needsCompanion) setOf(SpecialNames.DEFAULT_NAME_FOR_COMPANION_OBJECT) else emptySet()
    }

    override fun generateNestedClassLikeDeclaration(
        owner: FirClassSymbol<*>,
        name: Name,
        context: NestedClassGenerationContext,
    ): FirClassLikeSymbol<*>? {
        if (name != SpecialNames.DEFAULT_NAME_FOR_COMPANION_OBJECT || !owner.isComponentClass()) return null

        val componentType = session.selfParameterizedType(COMPONENT_TYPE_CLASS_ID, owner) ?: return null
        return createCompanionObject(owner, FleksPluginKey) { superType(componentType) }.symbol
    }

    override fun getCallableNamesForClass(classSymbol: FirClassSymbol<*>, context: MemberGenerationContext) = when {
        classSymbol.isGeneratedCompanion() -> setOf(SpecialNames.INIT)
        classSymbol.isComponentClass() && !classSymbol.declaresType() -> setOf(TYPE_FUNCTION_NAME)
        else -> emptySet()
    }

    override fun generateConstructors(context: MemberGenerationContext): List<FirConstructorSymbol> {
        val owner = context.owner
        if (!owner.isGeneratedCompanion()) return emptyList()
        return listOf(createDefaultPrivateConstructor(owner, FleksPluginKey).symbol)
    }

    override fun generateFunctions(
        callableId: CallableId,
        context: MemberGenerationContext?,
    ): List<FirNamedFunctionSymbol> {
        val owner = context?.owner ?: return emptyList()
        if (callableId.callableName != TYPE_FUNCTION_NAME || !owner.isComponentClass()) return emptyList()

        val returnType = session.selfParameterizedType(COMPONENT_TYPE_CLASS_ID, owner) ?: return emptyList()
        val function = createMemberFunction(owner, FleksPluginKey, TYPE_FUNCTION_NAME, returnType) {
            status { isOverride = true }
        }
        return listOf(function.symbol)
    }
}

private class FleksExtensionRegistrar : FirExtensionRegistrar() {
    override fun ExtensionRegistrarContext.configurePlugin() {
        +::FleksSupertypeGenerationExtension
        +::FleksDeclarationGenerationExtension
    }
}

private class FleksIrGenerationExtension(private val configuration: CompilerConfiguration) : IrGenerationExtension {
    override fun generate(moduleFragment: IrModuleFragment, pluginContext: IrPluginContext) {
        moduleFragment.acceptChildrenVoid(FleksIrVisitor(pluginContext, configuration))
    }
}

/** Fills the bodies of the declarations that were generated in FIR. */
@OptIn(UnsafeDuringIrConstructionAPI::class)
private class FleksIrVisitor(
    private val ctx: IrPluginContext,
    private val configuration: CompilerConfiguration,
) : IrVisitorVoid() {
    private val componentTypeSymbol by lazy {
        ctx.finderForBuiltins().findClass(COMPONENT_TYPE_CLASS_ID).also {
            if (it == null) {
                configuration.report(
                    CliDiagnostics.COMPILER_PLUGIN_INITIALIZATION_ERROR,
                    "Fleks Compiler Plugin: ComponentType not found on classpath — add Fleks as a dependency."
                )
            }
        }
    }

    override fun visitElement(element: IrElement) = element.acceptChildrenVoid(this)

    override fun visitClass(declaration: IrClass) {
        declaration.acceptChildrenVoid(this)

        if (!declaration.hasAnnotation(COMPONENT_ANNOTATION_FQN)) return
        val companion = declaration.companionObject() ?: return

        declaration.generatedTypeFunction()?.let { function ->
            function.body = DeclarationIrBuilder(ctx, function.symbol).irBlockBody {
                +irReturn(irGetObject(companion.symbol))
            }
        }

        companion.delegateToComponentType(declaration)
    }

    private fun IrClass.generatedTypeFunction(): IrSimpleFunction? = declarations
        .filterIsInstance<IrSimpleFunction>()
        .singleOrNull { it.name == TYPE_FUNCTION_NAME && it.origin is IrDeclarationOrigin.GeneratedByPlugin }

    /**
     * Makes the companion extend `ComponentType<component>` and let its primary constructor call the super constructor.
     * A generated companion already has the supertype and only needs the constructor body. For a user defined
     * companion, the constructor still delegates to `Any`, so it gets replaced here. FIR2IR also keeps `Any` as supertype.
     */
    private fun IrClass.delegateToComponentType(component: IrClass) {
        val componentTypeSymbol = componentTypeSymbol ?: return // error is already reported
        val ctor = constructors.singleOrNull { it.isPrimary } ?: return
        val superCtor = componentTypeSymbol.owner.constructors.singleOrNull { it.isPrimary } ?: return

        val isGenerated = origin is IrDeclarationOrigin.GeneratedByPlugin
        val builder = DeclarationIrBuilder(ctx, ctor.symbol)
        fun superCall() = builder.irDelegatingConstructorCall(superCtor).also {
            it.typeArguments[0] = component.defaultType
        }

        if (isGenerated) {
            if (ctor.body == null) ctor.body = builder.irBlockBody { +superCall() }
            return
        }

        if (superTypes.none { it.classOrNull == componentTypeSymbol }) {
            superTypes += componentTypeSymbol.typeWith(component.defaultType)
        }
        // the class supertype must be the only one that is not an interface
        superTypes = superTypes.filterNot { it.isAny() }
        (ctor.body as? IrBlockBody)?.statements?.replaceAll {
            if (it is IrDelegatingConstructorCall && it.symbol != superCtor.symbol) superCall() else it
        }
    }
}

@OptIn(ExperimentalCompilerApi::class)
class FleksCompilerPlugin : CompilerPluginRegistrar() {
    override val pluginId: String = FLEKS_PLUGIN_ID
    override val supportsK2: Boolean = true

    override fun ExtensionStorage.registerExtensions(configuration: CompilerConfiguration) {
        FirExtensionRegistrarAdapter.registerExtension(FleksExtensionRegistrar())
        IrGenerationExtension.registerExtension(FleksIrGenerationExtension(configuration))
    }
}
